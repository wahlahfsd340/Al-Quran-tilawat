const URDU_DIGITS = '۰۱۲۳۴۵۶۷۸۹';
const Ctx = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('lang') === 'ur' ? 'ur' : 'en'; } catch { return 'en'; }
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ur' ? 'rtl' : 'ltr';
    try { localStorage.setItem('lang', lang); } catch { /* ignore */ }
  }, [lang]);

  const t = useCallback((key, vars = {}) => {
    const s = DICT[lang][key] ?? DICT.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
  }, [lang]);

  // Numbers: Urdu digits in Urdu mode
  const n = useCallback((x) => (lang === 'ur' ? String(x).replace(/\d/g, (d) => URDU_DIGITS[d]) : String(x)), [lang]);

  // Turn an ApiError into a friendly message in the current language
  const tErr = useCallback((e) => {
    const code = e?.code || 'generic';
    const key = `err_${code === 'load_failed' ? 'load' : code}`;
    return DICT[lang][key] ? t(key) : t('err_generic');
  }, [lang, t]);

  const toggle = () => setLang((l) => (l === 'en' ? 'ur' : 'en'));
  return <Ctx.Provider value={{ lang, t, n, tErr, toggle }}>{children}</Ctx.Provider>;
}

export const useLang = () => useContext(Ctx);
